import pytest

from two_sum import two_sum

@pytest.mark.parametrize(
    "arr, k, expected",
    [
        # Примеры из условия
        ([1, 3, 4, 10], 7, (1, 2)),
        ([5, 5, 1, 4], 10, (0, 1)),

        # Минимальный список
        ([2, 7], 9, (0, 1)),

        # Отрицательные числа и отрицательная сумма
        ([-8, -3, -5, -1], -4, (1, 3)),

        # Ноль входит в ответ
        ([0, 4, 9], 4, (0, 1)),

        # Пара из двух нулей
        ([0, 3, 0], 0, (0, 2)),

        # Нельзя использовать один элемент дважды
        ([3, 2, 4], 6, (1, 2)),

        # Ответ на первом и последнем индексах
        ([8, 1, 3, 5, 2], 10, (0, 4)),

        # Много всего
        ([4, -6, 7, 4, 0, 9, -5, 3], 2, (2, 6)),
    ],
)
def test_two_sum(arr, k, expected):
    assert two_sum(arr, k) == expected
    
if __name__ == "__main__":
    pytest.main([__file__, "-v"])